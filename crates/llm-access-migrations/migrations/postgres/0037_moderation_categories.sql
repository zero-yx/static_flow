-- Keyword moderation risk categories.
--
-- Adds a category taxonomy and classifies keywords under it. A keyword may
-- belong to several categories (category_codes is a JSONB array of codes), and
-- a ban record captures the categories of the keyword that fired
-- (matched_categories). Categories are managed separately from keywords so the
-- taxonomy can grow without touching keyword rows.

CREATE TABLE IF NOT EXISTS llm_moderation_categories (
    code TEXT PRIMARY KEY CHECK (length(code) > 0),
    label TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    severity TEXT NOT NULL DEFAULT 'medium'
        CHECK (severity IN ('critical', 'high', 'medium', 'low')),
    created_at_ms BIGINT NOT NULL CHECK (created_at_ms >= 0)
);

ALTER TABLE llm_moderation_keywords
    ADD COLUMN IF NOT EXISTS category_codes JSONB NOT NULL DEFAULT '[]'::jsonb;

ALTER TABLE llm_moderation_banned_sessions
    ADD COLUMN IF NOT EXISTS matched_categories JSONB NOT NULL DEFAULT '[]'::jsonb;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'ck_llm_moderation_keywords_category_codes_array'
    ) THEN
        ALTER TABLE llm_moderation_keywords
            ADD CONSTRAINT ck_llm_moderation_keywords_category_codes_array
            CHECK (jsonb_typeof(category_codes) = 'array');
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'ck_llm_moderation_banned_sessions_matched_categories_array'
    ) THEN
        ALTER TABLE llm_moderation_banned_sessions
            ADD CONSTRAINT ck_llm_moderation_banned_sessions_matched_categories_array
            CHECK (jsonb_typeof(matched_categories) = 'array');
    END IF;
END $$;

-- GIN index so "which keywords reference category X" (delete guard) and
-- category-filtered keyword queries stay fast as the keyword set grows.
CREATE INDEX IF NOT EXISTS idx_llm_moderation_keywords_category_codes
    ON llm_moderation_keywords USING gin (category_codes jsonb_path_ops);

